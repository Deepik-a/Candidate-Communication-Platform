"""
Candidate Service — Application layer use cases.
Single Responsibility: one class per use case group.
Open/Closed: extensible via repository interface.
"""

from typing import List, Optional, Tuple
from apps.candidates.domain.entities import CandidateEntity, MessageStatus
from apps.candidates.domain.repositories import CandidateRepositoryInterface


class CandidateService:
    """
    Application service coordinating candidate use cases.
    Follows SRP — delegates persistence to repository, handles business logic.
    """

    def __init__(self, repository: CandidateRepositoryInterface):
        self._repository = repository

    def list_candidates(
        self,
        search: Optional[str] = None,
        page: int = 1,
        page_size: int = 10,
    ) -> Tuple[List[CandidateEntity], int]:
        """List candidates with optional search and pagination."""
        return self._repository.get_all(search=search, page=page, page_size=page_size)

    def get_candidate(self, candidate_id: int) -> Optional[CandidateEntity]:
        """Retrieve a single candidate by primary key."""
        return self._repository.get_by_id(candidate_id)

    def create_candidate(
        self,
        full_name: str,
        mobile_number: str,
        email: Optional[str] = None,
    ) -> CandidateEntity:
        """Create a new candidate — sets default status to NA."""
        entity = CandidateEntity(
            id=None,
            candidate_id='',       # Generated by ORM
            full_name=full_name,
            mobile_number=mobile_number,
            email=email,
            last_message_date=None,
            status=MessageStatus.NA,
        )
        return self._repository.create(entity)

    def update_candidate(
        self,
        candidate_id: int,
        full_name: Optional[str] = None,
        mobile_number: Optional[str] = None,
        email: Optional[str] = None,
    ) -> Optional[CandidateEntity]:
        """Partially update candidate details."""
        existing = self._repository.get_by_id(candidate_id)
        if not existing:
            return None
        if full_name is not None:
            existing.full_name = full_name
        if mobile_number is not None:
            existing.mobile_number = mobile_number
        if email is not None:
            existing.email = email
        return self._repository.update(existing)

    def delete_candidate(self, candidate_id: int) -> bool:
        """Delete a single candidate."""
        return self._repository.delete(candidate_id)

    def bulk_delete_candidates(self, ids: List[int]) -> int:
        """Delete multiple candidates at once."""
        return self._repository.bulk_delete(ids)
